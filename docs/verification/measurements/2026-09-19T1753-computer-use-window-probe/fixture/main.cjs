const {app,BrowserWindow,Tray,Menu,nativeImage,ipcMain}=require('electron');
const fs=require('node:fs');
const path=require('node:path');
app.setPath('userData',path.join(__dirname,'user-data'));
app.setName('CUA Tray Probe');
const log=m=>fs.appendFileSync(path.join(__dirname,'probe.log'),new Date().toISOString()+' '+m+'\n');
let win,tray;
app.whenReady().then(()=>{
 app.dock?.hide();
 win=new BrowserWindow({width:600,height:340,title:'CUA Tray Probe',webPreferences:{preload:path.join(__dirname,'preload.cjs'),contextIsolation:true,nodeIntegration:false}});
 const icon=nativeImage.createFromDataURL('data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=');
 tray=new Tray(icon);tray.setTitle('CUA TEST');tray.setToolTip('Isolated Electron native tray probe');
 const menu=()=>Menu.buildFromTemplate([{label:'CUA probe native menu',enabled:false},{label:'Show probe window',click:()=>win.show()},{label:'Quit probe',click:()=>app.quit()}]);
 tray.on('click',()=>tray.popUpContextMenu(menu()));tray.on('right-click',()=>tray.popUpContextMenu(menu()));
 ipcMain.on('hide-probe',()=>{log('hide requested; restoring in 30 seconds');win.hide();setTimeout(()=>{win.show();log('window restored');},30000);});
 ipcMain.on('quit-probe',()=>app.quit());
 win.on('show',()=>log('window show'));win.on('hide',()=>log('window hide'));
 win.loadFile(path.join(__dirname,'index.html'));log('ready Electron '+process.versions.electron+' pid '+process.pid);
});
app.on('window-all-closed',()=>app.quit());
app.on('before-quit',()=>log('quit'));
